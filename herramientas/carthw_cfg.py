# pico/carthw.cfg -> pico/carthw_cfg.c: la tabla de cartuchos especiales de PicoDrive como un texto de C (lo mismo
# que tools/make_carthw_c.c de PicoDrive, sin tener que compilarlo).
#     python herramientas/carthw_cfg.py picodrive/pico/carthw.cfg picodrive/pico/carthw_cfg.c
import sys


def convertir(entrada, salida):
    lineas = ["/* generated by carthw_cfg.py, do not modify */", "static const char builtin_carthw_cfg[] ="]
    with open(entrada, "r", encoding="latin-1") as f:
        for linea in f:
            p = linea.lstrip()
            if not p or p.startswith("#"):
                continue
            if p.startswith("["):
                p = "[]"
            d = []
            comillas = False
            for c in p:
                if not comillas and c == "#":
                    break
                if not comillas and c.isspace():
                    continue
                if c == '"':
                    comillas = not comillas
                    d.append("\\")
                d.append(c)
            lineas.append('  "%s\\n"' % "".join(d))
    lineas.append(";")
    with open(salida, "w", encoding="latin-1", newline="\n") as f:
        f.write("\n".join(lineas) + "\n")


if __name__ == "__main__":
    convertir(sys.argv[1], sys.argv[2])
